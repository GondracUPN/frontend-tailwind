import { cardTypeFromProduct, parseBankAmount, parseBankOperation, parseBankOperations } from './bankOperationParser';

const interbankReceipt = (number, amount, currency = 'S/', sourceCurrency = 'Soles', account = '285 3147915690') => `Interbank Servicio al Cliente <servicioalcliente@netinterbank.com.pe>
23 oct 2026, 2:02 p.m.
Interbank
Hola WALTER, te enviamos tu

Constancia de pago

Código de operación

${number}

Fecha y hora

23 Oct 2026

02:02 PM

Cuenta cargo

Cuenta Simple

${sourceCurrency}

${account}

Tarjeta de crédito

Visa Platinum

Soles

422224******7645

Moneda y monto

${currency} ${amount}

Celular en mano
En Interbank, nunca te pediremos tu clave.`;

test('detecta las tres constancias Interbank pegadas desde Gmail sin confundir la moneda de la tarjeta', () => {
  const result = parseBankOperations([
    interbankReceipt('0523604', '800.00'),
    interbankReceipt('0524863', '96.50', 'US$', 'Dólares', '285 3147915703'),
    interbankReceipt('0525728', '131.37'),
  ].join('\n\n'));

  expect(result.errors).toEqual([]);
  expect(result.total).toBe(3);
  expect(result.operations).toEqual([
    expect.objectContaining({ amount: 800, chargedAmount: 800, currency: 'PEN', chargedCurrency: 'PEN', sourceLast4: '5690', operationNumber: '0523604' }),
    expect.objectContaining({ amount: 96.5, chargedAmount: 96.5, currency: 'USD', chargedCurrency: 'USD', sourceLast4: '5703', operationNumber: '0524863' }),
    expect.objectContaining({ amount: 131.37, chargedAmount: 131.37, currency: 'PEN', chargedCurrency: 'PEN', sourceLast4: '5690', operationNumber: '0525728' }),
  ]);
  result.operations.forEach((operation) => expect(operation).toMatchObject({
    kind: 'card_payment', date: '2026-10-23', cardType: 'interbank', sourceBank: 'interbank',
    productName: 'Visa Platinum', cardLast4: '7645', exchangeRate: null,
  }));
});

test('rechaza constancias incompletas o sin importe cobrado en la moneda de origen', () => {
  expect(parseBankOperation(interbankReceipt('0523604', '800.00').replace('23 Oct 2026', ''))).toMatchObject({ ok: false });
  expect(parseBankOperation(interbankReceipt('0523604', '800.00').replace('Tarjeta de crédito', 'Servicio'))).toMatchObject({ ok: false });
  expect(parseBankOperation(interbankReceipt('0523604', '800.00', 'US$'))).toMatchObject({ ok: false });
});

const SAMPLE = `Realizaste un pago a tu tarjeta de **S/ 400.00** desde tu **Cuenta digital**.

Monto pagado **S/ 400.00**
Operación realizada **Pago de tarjeta propia BCP**
Fecha y hora **30 de Julio de 2026 - 09:22 PM**
Pagado a **AMEX Black LATAM Pass**
**** 0962
Tipo de pago **Otro**
Desde **Cuenta digital**
**** 5091
Moneda **Soles**
Canal **Banca Móvil BCP**
Número de operación **06912552**`;

test('parses a BCP own-card payment email', () => {
  expect(parseBankOperation(SAMPLE)).toEqual({
    ok: true,
    operation: {
      kind: 'card_payment',
      amount: 400,
      currency: 'PEN',
      chargedAmount: 400,
      chargedCurrency: 'PEN',
      exchangeRate: null,
      date: '2026-07-30',
      cardType: 'bcp_amex',
      productName: 'AMEX Black LATAM Pass',
      cardLast4: '0962',
      sourceBank: 'bcp',
      sourceLast4: '5091',
      operationNumber: '06912552',
    },
  });
});

test('reconoce un pago IO directo de dólares a dólares', () => {
  const result = parseBankOperation(`Fecha y hora: **Sábado, 05 Septiembre 2026 - 01:52 P. M.**
Empresa: **IO DE BCP**
Servicio: **PAGO DOLARES**
Titular del servicio: **Walter Gonzalo G.**
Código de usuario: **75135395**
Cuenta de origen: **Cuenta de ahorros**
**** 6124
**WALTER GONZALO**
Monto total: **$ 167.10**`);

  expect(result).toEqual({
    ok: true,
    operation: expect.objectContaining({
      amount: 167.1,
      chargedAmount: 167.1,
      chargedCurrency: 'USD',
      exchangeRate: null,
      date: '2026-09-05',
      sourceLast4: '6124',
    }),
  });
});

test('parses several pasted bank emails as a batch', () => {
  const second = SAMPLE
    .replace(/S\/ 400\.00/g, 'S/ 125.50')
    .replace('30 de Julio de 2026', '31 de Julio de 2026')
    .replace('06912552', '06912553');
  const result = parseBankOperations(`${SAMPLE}\n\n${second}`);

  expect(result.errors).toEqual([]);
  expect(result.total).toBe(2);
  expect(result.operations.map((operation) => operation.operationNumber)).toEqual(['06912552', '06912553']);
  expect(result.operations.map((operation) => operation.amount)).toEqual([400, 125.5]);
});

test('separa lotes mixtos de BCP e Interbank', () => {
  const result = parseBankOperations(`${SAMPLE}\n${interbankReceipt('0523604', '800.00')}\n${SAMPLE}`);
  expect(result.errors).toEqual([]);
  expect(result.operations.map((operation) => operation.sourceBank)).toEqual(['bcp', 'interbank', 'bcp']);
});

test('supports the separator generated by the Gmail userscript', () => {
  const result = parseBankOperations(`${SAMPLE}\n\n===== OPERACIÓN BANCARIA 2 =====\n\ntexto no reconocido`);

  expect(result.operations).toHaveLength(1);
  expect(result.errors).toHaveLength(1);
  expect(result.total).toBe(2);
});

